"""Generate Python-compatible character classes for the Rust core.

Run with the Python version shipped in the portable runtime (3.12, Unicode 15.0)
so `str.isspace`, `re` `\\w`/`\\d` and `str.isdecimal` match it exactly.
"""
import sys, unicodedata
from pathlib import Path


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None: start = cp
        if not ok and start is not None: out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out


def table(name, items):
    body = ''.join(f'({a:#x},{b:#x}),' for a, b in items)
    return f'pub static {name}: &[(u32, u32)] = &[{body}];\n'


digits = [(cp, unicodedata.decimal(chr(cp))) for cp in range(0x110000) if chr(cp).isdecimal()]
zero_runs = []
for cp, value in digits:
    if value == 0: zero_runs.append(cp)
out = [f'// Generated by rust/tools/gen_unicode.py with Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.\n',
       f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";\n',
       table('PY_SPACE', ranges(str.isspace)),
       table('PY_WORD', ranges(lambda c: c.isalnum() or c == '_')),
       table('PY_DECIMAL', ranges(str.isdecimal))]
# Every decimal digit block is 0..9 in order; store the code point of each block's zero.
assert all(unicodedata.decimal(chr(z + i)) == i for z in zero_runs for i in range(10))
out.append('pub static PY_DECIMAL_ZEROS: &[u32] = &[' + ''.join(f'{z:#x},' for z in zero_runs) + '];\n')
Path(sys.argv[1]).write_text(''.join(out))
print(len(digits), 'decimal digits;', len(zero_runs), 'blocks')
