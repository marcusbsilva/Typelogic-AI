//! Dependency-free SHA-256, SHA-512, MD5 and BLAKE2s (variable digest length), checked against `hashlib`.
//! MD5 exists only for the project's compatibility fingerprints; it is not a security primitive.

pub fn hex(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push(HEX[(b >> 4) as usize] as char);
        s.push(HEX[(b & 15) as usize] as char);
    }
    s
}

fn pad_be(data: &[u8], block: usize, len_bytes: usize) -> Vec<u8> {
    let bit_len = (data.len() as u128) * 8;
    let mut m = Vec::with_capacity(data.len() + block * 2);
    m.extend_from_slice(data);
    m.push(0x80);
    while m.len() % block != block - len_bytes {
        m.push(0);
    }
    let len = bit_len.to_be_bytes();
    m.extend_from_slice(&len[16 - len_bytes..]);
    m
}

